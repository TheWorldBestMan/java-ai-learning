const assert = require('assert');
const tools = require('../assets/progress.js');
const empty = () => ({version:1, xp:0, chapters:{}, exercises:{}, quiz:{}, labs:{}, interview:{}, review:{}});
const local = empty(), incoming = empty();
local.exercises.env = {code:'本机草稿'};
local.quiz.env = {answers:{0:1}};
local.chapters.env = {done:true};
incoming.exercises.env = {code:'备份草稿'};
incoming.exercises.other = {code:'新增草稿'};
incoming.chapters.env = {done:false};
incoming.chapters.other = {done:true};
incoming.quiz.env = {answers:{0:0,1:2}};
const backup = {format:'java-ai-learning-backup',version:1,state:incoming,labs:{}};
assert.strictEqual(tools.validate(backup), incoming);
const merged = tools.merge(local,incoming);
assert.strictEqual(merged.exercises.env.code, '本机草稿');
assert.strictEqual(merged.exercises.other.code, '新增草稿');
assert(merged.chapters.env.done && merged.chapters.other.done);
assert.deepStrictEqual(merged.quiz.env.answers, {0:1,1:2});
assert.throws(() => tools.validate({...backup,version:99}));
assert.throws(() => tools.validate({...backup,state:{...incoming,quiz:{env:{answers:[]}}}}));
assert.strictEqual(local.exercises.env.code, '本机草稿');
console.log('OK: backup validation, merge, conflicts and compatibility');
